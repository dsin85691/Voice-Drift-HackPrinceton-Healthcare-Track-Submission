"""Build test_audio/: clean, noisy and deliberately bad WAVs for trying the demo and the quality gate.

    python tools/make_test_audio.py            # writes test_audio/ and test_audio/README.md

Everything is derived from the bundled synthetic readings in server/demo_assets/ (offline text-to-speech, no real
person) and noise generated by the app's own server/pipeline/noise.py, so the folder is reproducible and safe to
share. Each file is run through the app's quality gate and the measured verdict is written to the README.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from server.config import get_config  # noqa: E402
from server.pipeline import decode, noise, quality  # noqa: E402
from server.pipeline.decode import write_wav  # noqa: E402

SR = 16000
OUT = ROOT / "test_audio"


def full_mix(x, kind, snr, seed=0):
    m = quality.vad_mask(x)
    nz = noise.make_noise(kind, len(x), seed, ref=x)
    return noise.mix_interval(x, nz, 0.0, len(x) / SR, snr, m)


def main() -> None:
    src = ROOT / "server" / "demo_assets"
    normal = decode.decode_audio(src / "sample_normal.wav")
    slower = decode.decode_audio(src / "sample_changed.wav")
    files: dict[str, tuple[np.ndarray, str]] = {
        "clean/reading_normal.wav": (normal, "Standard passage, normal pace (same synthetic voice as the sample baseline)."),
        "clean/reading_slower.wav": (slower, "Same passage, read noticeably slower."),
        "noisy/reading_normal_pink_20dB.wav": (full_mix(normal, "pink", 20), "Pink noise over the whole reading, 20 dB SNR (mild)."),
        "noisy/reading_normal_pink_15dB.wav": (full_mix(normal, "pink", 15), "Pink noise over the whole reading, 15 dB SNR (noisy but usable)."),
        "noisy/reading_normal_babble_15dB.wav": (full_mix(normal, "babble_self", 15), "Babble over the whole reading, 15 dB SNR (noisy but usable)."),
        "noisy/reading_normal_pink_10dB.wav": (full_mix(normal, "pink", 10), "Pink noise over the whole reading, 10 dB SNR."),
        "noisy/reading_normal_babble_10dB.wav": (full_mix(normal, "babble_self", 10), "Babble (reversed same voice) over the whole reading, 10 dB SNR."),
        "noisy/reading_normal_babble_5dB.wav": (full_mix(normal, "babble_self", 5), "Babble over the whole reading, 5 dB SNR (heavy)."),
        "noisy/reading_normal_speechshaped_10dB.wav": (full_mix(normal, "speech_shaped", 10), "Speech-shaped steady noise, 10 dB SNR."),
    }
    m = quality.vad_mask(normal)
    nz = noise.make_noise("babble_self", len(normal), 0, ref=normal)
    files["noisy/reading_normal_babble_10dB_14-30s.wav"] = (
        noise.mix_interval(normal, nz, 14.0, 30.0, 10, m), "Babble at 10 dB only between 14 s and 30 s (the noise-demo setting).")
    n30 = 30 * SR
    files["noise_only/pink_30s.wav"] = (
        (0.05 * noise.make_noise("pink", n30, 1) / (np.std(noise.make_noise("pink", n30, 1)) + 1e-9)).astype(np.float32),
        "Pink noise alone, for the Lab's 'noise file' option.")
    bab = noise.make_noise("babble_self", n30, 2, ref=normal)
    files["noise_only/babble_30s.wav"] = ((0.05 * bab / (np.std(bab) + 1e-9)).astype(np.float32),
                                         "Babble alone (reversed synthetic voice), for the Lab's 'noise file' option.")
    rng = np.random.default_rng(0)
    files["quality/silence_30s.wav"] = ((1e-4 * rng.standard_normal(n30)).astype(np.float32), "Near-silence: should be rejected (no speech).")
    files["quality/too_short_10s.wav"] = (normal[: 10 * SR].copy(), "10 s of speech: should be rejected (minimum 20 s).")
    ms = np.zeros(45 * SR, np.float32)
    ms[: 12 * SR] = normal[: 12 * SR]
    files["quality/mostly_silent_45s.wav"] = (ms, "12 s of speech then 33 s of silence: should be rejected (too little speech).")
    clip = np.clip(normal / (np.max(np.abs(normal)) + 1e-9) * 6.0, -1.0, 1.0).astype(np.float32)
    files["quality/clipped.wav"] = (clip, "Reading amplified until it clips: should be rejected (distorted).")

    cfg = get_config()
    rows = []
    for rel, (x, desc) in files.items():
        p = OUT / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        write_wav(p, np.asarray(x, np.float32))
        y = decode.decode_audio(p)                       # measure what was actually written
        q = quality.assess(y, cfg).to_json()
        dur = len(y) / SR
        verdict = q["verdict"]
        reasons = list(q["reasons"])
        if dur < cfg.audio["min_s"]:
            verdict, reasons = "REJECT", ["recording too short"]
        rows.append((rel, f"{dur:.0f} s", verdict, ", ".join(reasons) or "-", f"{q['snr_db']:.0f}", desc))
        print(f"{rel:48s} {dur:5.1f}s  {verdict:6s} {', '.join(reasons)}")

    md = ["# Test audio", "",
          "Clean, noisy and deliberately bad recordings for trying Voice Drift without a microphone. Built by "
          "`python tools/make_test_audio.py`.", "",
          "**All speech here is synthetic** (the bakery passage read by the offline Windows text-to-speech voice "
          "\"Microsoft David\", from `server/demo_assets/`). Noise comes from the app's own generator "
          "(`server/pipeline/noise.py`): pink noise, speech-shaped noise, and \"babble\" made from the same voice played "
          "reversed. No real person's voice and no dataset audio is included.", "",
          "## How to use", "",
          "- **Noise-robustness lab:** Results -> \"Try your own recording\": upload `clean/reading_normal.wav` and either "
          "pick a built-in noise or upload a file from `noise_only/`. Use the profile **Sample speaker (synthetic voice)** "
          "(click \"Analyze sample recording\" once first so its baseline exists).",
          "- **Pre-mixed noisy versions:** `noisy/` holds the same reading with noise already added, for comparing against "
          "`clean/reading_normal.wav`.",
          "- **Quality gate:** the files in `quality/` should each be rejected with a clear reason.", "",
          "## Files (verdicts measured by the app's quality gate when the files were generated)", "",
          "| File | Length | Quality verdict | Reasons | SNR estimate (dB) | What it is |", "|---|---|---|---|---|---|"]
    md += [f"| `{r[0]}` | {r[1]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} |" for r in rows]
    md += ["", "SNR in the file names is the mixing ratio over speech frames; the estimate column is the app's own "
           "rough estimate from the recording, so the two differ.", "",
           "Noise over the **whole** reading at 10 dB or below is rejected by the quality gate (it rejects recordings "
           "whose estimated SNR is under 12 dB). That is intended: the app refuses to score such recordings rather than "
           "guess. The noise-robustness demo therefore adds noise to an **interval** only (see the 14-30 s file), "
           "and the 15 dB files are the noisy-but-usable case."]
    (OUT / "README.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
